import { afterEach, beforeEach, describe, expect, it } from 'vitest';
import { mkdtempSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { parseEnvFile } from '../../dist/doctor/env-file.js';
import { generateTestKey } from '../helpers/rsa-keys.js';
import { createStubGithub, type StubGithub } from './helpers/stub-github.js';
import { runCli } from './helpers/run-cli.js';

// `--dotenv-file` parses a dotenv-style file **as data**: NAME=value,
// quotes, comments, `=` inside values, and — critically — no execution
// of anything the file contains. (Named --dotenv-file, not --env-file:
// Node.js itself intercepts a literal `--env-file` anywhere in argv —
// see the comment above `parseDoctorArgs` in src/doctor/config.ts.)
// Unit tests exercise `parseEnvFile` directly (built, from dist/); the
// tests at the bottom wire `--dotenv-file` through the real, spawned CLI
// end to end.

describe('parseEnvFile: unit', () => {
  it('parses simple NAME=value lines', () => {
    expect(parseEnvFile('FOO=bar\nBAZ=qux\n')).toEqual({ FOO: 'bar', BAZ: 'qux' });
  });

  it('ignores blank lines and full-line comments', () => {
    const content = ['# a comment', '', 'FOO=bar', '   # indented comment', '', 'BAZ=qux'].join('\n');
    expect(parseEnvFile(content)).toEqual({ FOO: 'bar', BAZ: 'qux' });
  });

  it('supports an optional leading "export "', () => {
    expect(parseEnvFile('export FOO=bar')).toEqual({ FOO: 'bar' });
  });

  it('trims an unquoted value', () => {
    expect(parseEnvFile('FOO =   bar  ')).toEqual({ FOO: 'bar' });
  });

  it('keeps "=" occurring inside an unquoted value (only the first "=" splits)', () => {
    expect(parseEnvFile('FEEDBACK_APP_URL=https://example.com/?a=b=c')).toEqual({
      FEEDBACK_APP_URL: 'https://example.com/?a=b=c',
    });
  });

  it('keeps "=" occurring inside a quoted value', () => {
    expect(parseEnvFile('FOO="a=b=c"')).toEqual({ FOO: 'a=b=c' });
  });

  it('double-quoted values: unescapes \\n, \\", \\\\', () => {
    const content = String.raw`FOO="line one\nline two \"quoted\" \\ done"`;
    expect(parseEnvFile(content)).toEqual({ FOO: 'line one\nline two "quoted" \\ done' });
  });

  it('single-quoted values are literal — no escape processing', () => {
    const content = String.raw`FOO='no \n escapes here'`;
    expect(parseEnvFile(content)).toEqual({ FOO: 'no \\n escapes here' });
  });

  it('a quoted value may itself contain a "#" without it being treated as a comment', () => {
    expect(parseEnvFile('FOO="has a # inside"')).toEqual({ FOO: 'has a # inside' });
  });

  it('the last assignment of a repeated name wins', () => {
    expect(parseEnvFile('FOO=one\nFOO=two\n')).toEqual({ FOO: 'two' });
  });

  it('ignores a line that is not NAME=value or a comment', () => {
    expect(parseEnvFile('this is not an assignment\nFOO=bar\n')).toEqual({ FOO: 'bar' });
  });

  it('never executes a value that looks like a shell command — it is stored as the literal string', () => {
    const content = 'FOO=$(echo pwned)\nBAR=`echo also-pwned`\n';
    expect(parseEnvFile(content)).toEqual({ FOO: '$(echo pwned)', BAR: '`echo also-pwned`' });
  });

  it('handles \\r\\n line endings', () => {
    expect(parseEnvFile('FOO=bar\r\nBAZ=qux\r\n')).toEqual({ FOO: 'bar', BAZ: 'qux' });
  });

  it('returns an empty object for an empty file', () => {
    expect(parseEnvFile('')).toEqual({});
  });
});

describe('--dotenv-file: wired through the real CLI', () => {
  const key = generateTestKey();
  let stub: StubGithub;
  let dir: string;

  beforeEach(async () => {
    stub = await createStubGithub();
    stub.setLabels(['source:in-app', 'app:example-app', 'env:uat']);
    dir = mkdtempSync(join(tmpdir(), 'feedback-doctor-envfile-'));
  });

  afterEach(async () => {
    await stub.close();
  });

  // The private key and FEEDBACK_GITHUB_API_BASE_URL never appear in a
  // written dotenv file in this describe block: resolveConfig() refuses
  // a --dotenv-file that contains the key outright (its own test below),
  // and silently never reads the API base URL from one at all (it can
  // only come from --api-base-url or the real environment — see
  // src/doctor/config.ts's comment on API_BASE_URL_ENV_VAR) — so both
  // are supplied through the real environment here instead, the way a
  // person actually would.
  function writeEnvFile(name: string, extraLines: string[] = []): string {
    const path = join(dir, name);
    const content = [
      '# generated by test/bin/env-file.test.ts',
      'FEEDBACK_GITHUB_CLIENT_ID=Iv1.testclient',
      'FEEDBACK_GITHUB_INSTALLATION_ID=12345',
      'FEEDBACK_INTAKE_REPOSITORY=acme/intake-repo',
      'FEEDBACK_APP_URL=https://app.example',
      'FEEDBACK_ORIGINS=https://app.example,https://staging.app.example',
      'FEEDBACK_LABELS=source:in-app,app:example-app,env:uat',
      ...extraLines,
    ].join('\n');
    writeFileSync(path, content, 'utf8');
    return path;
  }

  /** The two settings that must come from the real environment only —
   * merged with whatever the individual test passes for the rest of it. */
  function realEnv(overrides: Record<string, string> = {}): Record<string, string> {
    return {
      FEEDBACK_GITHUB_PRIVATE_KEY: key.pkcs1Pem,
      FEEDBACK_GITHUB_API_BASE_URL: stub.url,
      ...overrides,
    };
  }

  it('supplies every required setting except the key and the API base URL from the file', async () => {
    const path = writeEnvFile('.env');

    const result = await runCli(['doctor', '--dotenv-file', path], realEnv());

    expect(result.exitCode).toBe(0);
    expect(result.stdout).toContain('[PASS] required-names');
    expect(result.stdout).toContain('[PASS] key-parses');
    expect(result.stdout).toContain('[PASS] token-mint');
  });

  it('a value already present in the real environment takes precedence over the file', async () => {
    const path = writeEnvFile('.env', ['FEEDBACK_APP_URL=https://from-file.example']);

    // https://from-file.example is not in FEEDBACK_ORIGINS, so if the
    // file's value won, app-url-in-origins would FAIL. It must not.
    const result = await runCli(
      ['doctor', '--dotenv-file', path],
      realEnv({ FEEDBACK_APP_URL: 'https://app.example' }),
    );

    expect(result.exitCode).toBe(0);
    expect(result.stdout).toContain('[PASS] app-url-in-origins');
  });

  it('refuses a --dotenv-file that contains FEEDBACK_GITHUB_PRIVATE_KEY, before any check runs', async () => {
    const escapedKey = key.pkcs1Pem.replace(/\n/g, '\\n');
    const path = writeEnvFile('.env', [`FEEDBACK_GITHUB_PRIVATE_KEY="${escapedKey}"`]);

    // The key is supplied correctly through the real environment too, to
    // prove the file's mere *presence* of the name is what's refused —
    // not merely "the key is missing from everywhere else".
    const result = await runCli(['doctor', '--dotenv-file', path], realEnv());

    expect(result.exitCode).toBe(2);
    expect(result.stdout).toBe('');
    expect(result.stderr).toContain(
      '--dotenv-file must not contain FEEDBACK_GITHUB_PRIVATE_KEY — the key comes from the real environment only',
    );
  });

  it('a --dotenv-file containing FEEDBACK_GITHUB_API_BASE_URL never redirects doctor away from the real environment value', async () => {
    // A poisoned line in a shared/committed dotenv file must not be able
    // to redirect the installation-token mint (which sends the signed
    // app JWT) anywhere. It is silently ignored, not merely overridden —
    // proven here by pointing the file at an address nothing listens on
    // and confirming the run still succeeds against the *real* env's stub.
    const path = writeEnvFile('.env', ['FEEDBACK_GITHUB_API_BASE_URL=http://127.0.0.1:1']);

    const result = await runCli(['doctor', '--dotenv-file', path], realEnv());

    expect(result.exitCode).toBe(0);
    expect(result.stdout).toContain('[PASS] token-mint');
  });
});
